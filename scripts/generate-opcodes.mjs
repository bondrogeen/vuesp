#!/usr/bin/env node
// Generates the C++ and TypeScript opcode tables from opcodes.yaml.
// Run: node scripts/generate-opcodes.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src/runner/bytecode/opcodes.yaml');
const cppOut = path.join(root, 'src/runner/bytecode/Opcode.h');
const tsOut = path.join(root, 'vue/src/lib/script/opcodes.ts');

function parseYaml(text) {
  const opcodes = [];
  let current = null;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.replace(/#.*$/, '').trimEnd();
    if (!line.trim()) continue;
    const nameMatch = line.match(/^\s*-\s+name:\s*([A-Z0-9_]+)\s*$/);
    if (nameMatch) {
      current = { name: nameMatch[1], code: null, operands: [], pop: 0, push: 0 };
      opcodes.push(current);
      continue;
    }
    if (!current) continue;
    const field = line.match(/^\s+([a-z_]+):\s*(.*?)\s*$/);
    if (!field) continue;
    const [, key, value] = field;
    if (key === 'code') current.code = Number.parseInt(value, 16);
    else if (key === 'operands') {
      const body = value.replace(/^\[/, '').replace(/\]$/, '').trim();
      current.operands = body ? body.split(',').map((item) => item.trim()).filter(Boolean) : [];
    } else if (key === 'pop') current.pop = Number.parseInt(value, 10);
    else if (key === 'push') current.push = Number.parseInt(value, 10);
  }
  for (const op of opcodes) {
    if (!Number.isInteger(op.code) || op.code < 0 || op.code > 0xff) {
      throw new Error(`Invalid or missing code for ${op.name}`);
    }
  }
  const names = new Set();
  const codes = new Set();
  for (const op of opcodes) {
    if (names.has(op.name)) throw new Error(`Duplicate opcode name: ${op.name}`);
    if (codes.has(op.code)) throw new Error(`Duplicate opcode code: 0x${op.code.toString(16)}`);
    names.add(op.name);
    codes.add(op.code);
  }
  return opcodes.sort((a, b) => a.code - b.code);
}

function cppOperandSize(operand) {
  if (
    operand === 'i8' ||
    operand === 'u8' ||
    operand === 'var8' ||
    operand === 'kind8' ||
    operand === 'argc8' ||
    operand === 'func8' ||
    operand === 'event8'
  ) {
    return 0; // 1 byte
  }
  if (operand === 'i16' || operand === 'u16' || operand === 'const16' || operand === 'name16') {
    return 1; // 2 bytes
  }
  if (operand === 'i32' || operand === 'u32' || operand === 'f32') {
    return 2; // 4 bytes
  }
  throw new Error(`Unknown operand type: ${operand}`);
}

function cppOperandLayout(op) {
  const count = op.operands.length;
  let sizes = 0;
  op.operands.forEach((operand, index) => {
    sizes |= cppOperandSize(operand) << (index * 2);
  });
  return { count, sizes };
}

function cpp(opcodes) {
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-opcodes.mjs from opcodes.yaml.');
  lines.push('// Do not edit by hand.');
  lines.push('#pragma once');
  lines.push('');
  lines.push('#include <stdint.h>');
  lines.push('');
  lines.push('namespace vuesp {');
  lines.push('namespace bytecode {');
  lines.push('');
  lines.push('enum class Opcode : uint8_t {');
  for (const op of opcodes) {
    lines.push(`  ${op.name} = 0x${op.code.toString(16).padStart(2, '0')},`);
  }
  lines.push('};');
  lines.push('');
  lines.push('struct OpcodeInfo {');
  lines.push('  Opcode op;');
  lines.push('  const char* name;');
  lines.push('  uint8_t pop;');
  lines.push('  uint8_t push;');
  lines.push('  uint8_t operandCount;');
  lines.push('  uint8_t operandSizes;  // 2 bits per operand: 0=1 byte, 1=2 bytes, 2=4 bytes');
  lines.push('};');
  lines.push('');
  for (const op of opcodes) {
    const layout = cppOperandLayout(op);
    lines.push(
      `static const OpcodeInfo kOpcode_${op.name} = {Opcode::${op.name}, "${op.name}", ${op.pop}, ${op.push}, ${layout.count}, ${layout.sizes}};`,
    );
  }
  lines.push('');
  lines.push('inline const OpcodeInfo* opcodeInfo(Opcode op) {');
  lines.push('  switch (op) {');
  for (const op of opcodes) {
    lines.push(
      `    case Opcode::${op.name}: return &kOpcode_${op.name};`,
    );
  }
  lines.push('    default: return nullptr;');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('}  // namespace bytecode');
  lines.push('}  // namespace vuesp');
  lines.push('');
  return lines.join('\n');
}

function ts(opcodes) {
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-opcodes.mjs from opcodes.yaml.');
  lines.push('// Do not edit by hand.');
  lines.push('');
  lines.push('export const Opcode = {');
  for (const op of opcodes) {
    lines.push(`  ${op.name}: 0x${op.code.toString(16).padStart(2, '0')},`);
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type OpcodeName = keyof typeof Opcode;');
  lines.push('');
  lines.push('export interface OpcodeInfo {');
  lines.push('  readonly code: number;');
  lines.push('  readonly operands: readonly string[];');
  lines.push('  readonly pop: number;');
  lines.push('  readonly push: number;');
  lines.push('}');
  lines.push('');
  lines.push('export const OPCODES: Readonly<Record<OpcodeName, OpcodeInfo>> = {');
  for (const op of opcodes) {
    const operands = op.operands.map((item) => `'${item}'`).join(', ');
    lines.push(
      `  ${op.name}: { code: 0x${op.code.toString(16).padStart(2, '0')}, operands: [${operands}], pop: ${op.pop}, push: ${op.push} },`,
    );
  }
  lines.push('};');
  lines.push('');
  lines.push('export function opcodeName(code: number): string {');
  lines.push('  const entry = Object.entries(OPCODES).find(([, info]) => info.code === code);');
  lines.push("  return entry ? entry[0] : `UNKNOWN_0x${code.toString(16)}`;");
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

const opcodes = parseYaml(fs.readFileSync(source, 'utf8'));
fs.mkdirSync(path.dirname(cppOut), { recursive: true });
fs.mkdirSync(path.dirname(tsOut), { recursive: true });
fs.writeFileSync(cppOut, cpp(opcodes));
fs.writeFileSync(tsOut, ts(opcodes));
console.log(`Generated ${opcodes.length} opcodes:`);
console.log(`  ${path.relative(root, cppOut)}`);
console.log(`  ${path.relative(root, tsOut)}`);
