#!/usr/bin/env node
// Generates C++ bytecode fixtures from the TypeScript compiler.
// Run: node scripts/generate-bytecode-vectors.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from '../vue/src/lib/script/compiler.ts';
import { DEFAULT_MANIFEST } from '../vue/src/lib/script/types.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(root, 'src/tests/fixtures/bytecode_vectors.h');

const fixtures = [
  { name: 'simple', source: '$u0 = 5; $u1 = $u0 + 3;' },
  { name: 'if_else', source: '$u0 = 1; if ($u0 > 0) { $p2 = 255; } else { $p2 = 0; }' },
  { name: 'while_loop', source: '$u0 = 0; while ($u0 < 5) { $u0 = $u0 + 1; }' },
  { name: 'ternary', source: '$u0 = $u1 > 0 ? 10 : 20;' },
  { name: 'wait', source: 'wait(100ms); $u0 = 1;' },
  { name: 'log', source: "log('hello', 42, $u0);" },
  { name: 'external', source: '$u0 = fade(2, 255, 1000);' },
  { name: 'data', source: "$display = 'hello';" },
  { name: 'handler', source: "on('btn') { $u0 = $e0 + $e1; }" },
  { name: 'call', source: "call('callee', 10, 20);" },
  { name: 'call_missing', source: "call('missing');" },
  { name: 'recursion', source: "call('recursion');" },
  { name: 'depth1', source: "call('depth2');" },
  { name: 'depth2', source: "call('depth3');" },
  { name: 'depth3', source: "call('depth4');" },
  { name: 'depth4', source: "call('depth5');" },
  { name: 'depth5', source: '$u0 = 1;' },
  { name: 'array', source: '$a0 = [1, 2, 3]; $u0 = $a0[1];' },
  { name: 'strings', source: "$s0 = 'a' + 'b'; $u0 = len($s0); $u1 = ord($s0); $s1 = chr(65);" },
  { name: 'array_ops', source: '$a0 = [1, 2, 3]; set($a0, 1, 9); $u0 = get($a0, 1); $u1 = len($a0);' },
  { name: 'float_math', source: '$f0 = 1.5; $f1 = $f0 * 2.0; $u0 = $f1 > 2.9 ? 1 : 0;' },
  { name: 'int_math', source: '$i0 = -5; $u0 = $i0 + 7;' },
  { name: 'break_continue', source: '$u0 = 0; while ($u0 < 10) { $u0 = $u0 + 1; if ($u0 == 3) { continue; } if ($u0 == 5) { break; } }' },
  { name: 'callee', source: '$u0 = $c0 + $c1;' },
  { name: 'port_read', source: '$p2 = 255; $u0 = $p2;' },
  { name: 'port_wide', source: '$p17 = 255; $u0 = $p17;' },
  { name: 'two_events', source: "on('btn', (gpio, value) => { $p13 = gpio; }); on('btn_c', (gpio, value, count) => { $p14 = count; });" },
  { name: 'data_read', source: "$display = 'hi'; $s0 = $display;" },
  { name: 'handler_return', source: "on('btn') { $p2 = 1; return; $p2 = 2; }" },
  { name: 'div_zero', source: '$u0 = 1 / 0;' },
];

function toArray(bytes) {
  const parts = [];
  for (let i = 0; i < bytes.length; i += 12) {
    parts.push(
      `  ${Array.from(bytes.slice(i, i + 12))
        .map((byte) => `0x${byte.toString(16).padStart(2, '0')}`)
        .join(', ')}`,
    );
  }
  return `{\n${parts.join(',\n')}\n}`;
}

const built = [];
for (const fixture of fixtures) {
  const result = compile(fixture.source, { manifest: DEFAULT_MANIFEST });
  if (!result.ok || !result.bytecode) {
    const errors = result.errors.map((err) => `${err.code}@${err.pos.line}:${err.pos.column} ${err.message}`).join('\n');
    throw new Error(`Fixture '${fixture.name}' failed:\n${errors}`);
  }
  built.push({ ...fixture, bytes: result.bytecode, stats: result.stats });
}

const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-bytecode-vectors.mjs.');
lines.push('// Do not edit by hand.');
lines.push('#pragma once');
lines.push('');
lines.push('#include <stdint.h>');
lines.push('');
lines.push('namespace vuesp {');
lines.push('namespace bytecode {');
lines.push('namespace fixtures {');
lines.push('');
lines.push('struct Vector {');
lines.push('  const char* name;');
lines.push('  const uint8_t* data;');
lines.push('  uint16_t size;');
lines.push('};');
lines.push('');
for (const fixture of built) {
  lines.push(`// ${fixture.name}: ${fixture.source}`);
  lines.push(`static const uint8_t k${fixture.name}[] = ${toArray(fixture.bytes)};`);
  lines.push('');
}
lines.push('static const Vector kAll[] = {');
for (const fixture of built) {
  lines.push(`  {"${fixture.name}", k${fixture.name}, (uint16_t)sizeof(k${fixture.name})},`);
}
lines.push('};');
lines.push('');
lines.push('static const uint16_t kAllCount = (uint16_t)(sizeof(kAll) / sizeof(kAll[0]));');
lines.push('');
lines.push('}  // namespace fixtures');
lines.push('}  // namespace bytecode');
lines.push('}  // namespace vuesp');
lines.push('');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${built.length} fixtures to ${path.relative(root, outPath)}`);
for (const fixture of built) {
  console.log(`  ${fixture.name}: ${fixture.bytes.length} bytes, stack ${fixture.stats?.stackMax ?? '?'}`);
}
